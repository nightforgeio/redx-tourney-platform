export function getLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (LANGS.includes(saved)) return saved;
  return 'hi';
}
export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
}
export function t(key, lang = getLang()) {
  return DICT[lang]?.[key] ?? DICT.en[key] ?? key;
}
export function applyI18n(root = document) {
  const lang = getLang();
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-t]').forEach((el) => { el.textContent = t(el.dataset.t, lang); });
  root.querySelectorAll('[data-t-ph]').forEach((el) => { el.placeholder = t(el.dataset.tPh, lang); });
  root.querySelectorAll('[data-t-tip]').forEach((el) => { el.title = t(el.dataset.tTip, lang); });
  root.querySelectorAll('[data-t-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.tAria, lang)); });
}